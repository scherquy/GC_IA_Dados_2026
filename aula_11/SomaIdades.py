'''
Receber 2 nomes, 2 idades e fazer a soma das idades
'''

nome1 = str(input("\nInforme o seu nome: "))
idade1 = int(input("Informe a sua idade: "))

nome2 = str(input("\nInforme o seu nome: "))
idade2 = int(input("Informe a sua idade: "))

soma_idades = idade1 + idade2

print(f"\nA soma das idades de {nome1} e {nome2} é {soma_idades} anos\n")